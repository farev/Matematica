/* brute2.c — second, independent implementation (MO 514690).
 *
 * Plain backtracking over unused values (as brute.c: every proper block of
 * every length 2..n-1 ending at the current position is checked), plus an
 * optional NECESSARY-condition filter on candidate values:
 *
 *   mode 0 : no filter (identical search space to brute.c).
 *   mode 1 : only what is literally proved in the MO answer (Bisceanu/te4):
 *            for every k >= 1 with 2^k < n,
 *              (a) a_t = a_{t-2^k} (mod 2^k)                  when t - 2^k >= 1,
 *              (b) the sum of the 2^k terms ending at t is an odd multiple
 *                  of 2^{k-1}                                when t >= 2^k.
 *   mode 2 : Lemma B(i) of REPORT.md as an explicit test against every earlier
 *            position, with a_0 := 0:
 *              v_2(v - a_x) = v_2(t - x)   for all 0 <= x < t.
 *
 * Because every filter is a proven necessary condition for goodness, the
 * search is exhaustive in every mode; only the node counts differ.  The
 * candidate values are generated by scanning 1..n, so the code path shares
 * nothing with tree.c's bit construction.
 *
 * Build: gcc -O2 -o brute2 brute2.c
 * Usage: ./brute2 n mode [-t seconds] [-p maxprint]
 */
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <time.h>

static int n, mode, maxprint = 5;
static int a[128];
static long P[129];
static uint64_t used[2];
static unsigned long long nodes = 0, solutions = 0;
static double time_cap = 0;
static clock_t c0;
static int aborted = 0, max_depth = 0;

static inline int v2(int x) { return __builtin_ctz(x); }   /* x != 0 */

static void rec(int t) {
    if (aborted) return;
    if (t > n) {
        solutions++;
        if (solutions <= (unsigned long long)maxprint) {
            printf("SOL:");
            for (int i = 1; i <= n; i++) printf(" %d", a[i]);
            printf("\n");
        }
        return;
    }
    for (int v = 1; v <= n; v++) {
        if (used[v >> 6] & (1ULL << (v & 63))) continue;
        if (mode == 1) {
            int ok = 1;
            for (int k = 1; (1 << k) < n; k++)
                if (t - (1 << k) >= 1 && ((v - a[t - (1 << k)]) & ((1 << k) - 1)) != 0) { ok = 0; break; }
            if (!ok) continue;
        } else if (mode == 2) {
            int ok = 1;
            for (int x = 0; x < t; x++)
                if (v2(v - a[x] + 0) != v2(t - x)) { ok = 0; break; }   /* a[0] = 0 */
            if (!ok) continue;
        }
        nodes++;
        if ((nodes & 0xFFFFF) == 0 && time_cap > 0 &&
            (double)(clock() - c0) / CLOCKS_PER_SEC > time_cap) { aborted = 1; return; }
        P[t] = P[t - 1] + v;
        int ok = 1;
        int Lmax = (t == n) ? n - 1 : t;
        for (int L = 2; L <= Lmax; L++)
            if ((P[t] - P[t - L]) % L == 0) { ok = 0; break; }
        if (ok && mode == 1) {                    /* sum form of the thread's lemma */
            for (int k = 1; (1 << k) < n && (1 << k) <= t; k++) {
                long S = P[t] - P[t - (1 << k)];
                if ((S % (1 << k)) != (1 << (k - 1))) { ok = 0; break; }
            }
        }
        if (!ok) continue;
        a[t] = v;
        if (t > max_depth) max_depth = t;
        used[v >> 6] |= 1ULL << (v & 63);
        rec(t + 1);
        used[v >> 6] &= ~(1ULL << (v & 63));
        if (aborted) return;
    }
}

int main(int argc, char **argv) {
    if (argc < 3) { fprintf(stderr, "usage: %s n mode [-t secs] [-p maxprint]\n", argv[0]); return 1; }
    n = atoi(argv[1]); mode = atoi(argv[2]);
    for (int i = 3; i < argc; i++) {
        if (!strcmp(argv[i], "-t")) time_cap = atof(argv[++i]);
        else if (!strcmp(argv[i], "-p")) maxprint = atoi(argv[++i]);
    }
    if (n < 2 || n > 127) { fprintf(stderr, "n out of range\n"); return 1; }
    c0 = clock();
    a[0] = 0; P[0] = 0; used[0] = 0; used[1] = 0;
    rec(1);
    double secs = (double)(clock() - c0) / CLOCKS_PER_SEC;
    printf("%s brute2 n=%d mode=%d good_permutations=%llu nodes=%llu maxdepth=%d time=%.3fs\n",
           aborted ? "INCOMPLETE(time cap)" : "COMPLETE", n, mode, solutions, nodes, max_depth, secs);
    return aborted ? 3 : 0;
}
