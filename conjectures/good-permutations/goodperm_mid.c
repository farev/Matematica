/*
 * goodperm_mid.c — engine C for good permutations of n = 2^m - 1:
 * three-region search order with early tail/middle checks.
 *
 * Facts used (NOTE.md): Lemma 2 (triangular residue structure, a_q = q with
 * q = (n+1)/2, and a_{t+q} = a_t XOR q for t < q) and Lemma 3 (only odd block
 * lengths need testing).  Positions 1..q-1 are assigned in the order
 * 1, q-1, 2, q-2, 3, q-3, ...; each assignment also fixes the partner position
 * t+q.  Hence at every stage the known positions form three intervals
 *   H = [1, j],   M = [q-j', q+j],   T = [2q-j', 2q-1],
 * and every odd block inside a known interval is tested as soon as it becomes
 * known.  At the last step everything is known and all blocks are re-tested.
 *
 * Usage: goodperm_mid n [sym] [maxreport] [L1,L2,...|-] [R,K]
 *   optional 4th argument: enforce only these odd block lengths (relaxation probe); "-" = all
 *   optional 5th argument R,K: work split — keep only a_1 with ((a_1>>1) mod K) == R
 *   sym = 1 breaks the complement symmetry by requiring a_1 < q (every orbit
 *   of the Klein group generated by reversal and complement has a member with
 *   a_1 < q; the count reported is then a count of such members, not of all
 *   good permutations).
 * Output: permutations found (up to maxreport), then
 *   "n=.. sym=.. count=.. nodes=.. time=..s"
 */
#include <stdio.h>
#include <stdlib.h>
#include <time.h>

#define MAXN 1023
static int n, q, m, sym, maxreport;
static int splitR = 0, splitK = 1; /* optional work split on a_1: keep only ((a_1>>1) mod K) == R */
static int a[MAXN + 2];
static long long pre[MAXN + 2];
static unsigned char used[MAXN + 2];
static int res[12][1024];
static unsigned char resused[12][1024];
static long long cnt = 0, nodes = 0;
static int order[MAXN];  /* order[s] = position assigned at step s */
static unsigned char useL[MAXN + 2]; /* which odd lengths are enforced */
static int nsteps;

static void report(void) {
    if (cnt <= maxreport) {
        for (int i = 1; i <= n; i++) printf("%d%c", a[i], i == n ? '\n' : ' ');
        fflush(stdout);
    }
}

/* set a[x] = v and update prefix sums from x on */
static void setval(int x, int v) {
    a[x] = v;
    for (int i = x; i <= n; i++) pre[i] = pre[i - 1] + a[i];
}

/* test odd blocks [s,e] inside [lo,hi] that END at e (s varies) */
static int check_ending(int lo, int e) {
    for (int L = 3; ; L += 2) {
        int s = e - L + 1;
        if (s < lo) return 1;
        if (L >= n) return 1;
        if (useL[L] && (pre[e] - pre[s - 1]) % L == 0) return 0;
    }
}
/* test odd blocks [s,e] inside [lo,hi] that START at s (e varies) */
static int check_starting(int s, int hi) {
    for (int L = 3; ; L += 2) {
        int e = s + L - 1;
        if (e > hi) return 1;
        if (L >= n) return 1;
        if (useL[L] && (pre[e] - pre[s - 1]) % L == 0) return 0;
    }
}
static int check_all(void) {
    for (int L = 3; L <= n - 1; L += 2)
        for (int s = 1; s + L - 1 <= n; s++)
            if (useL[L] && (pre[s + L - 1] - pre[s - 1]) % L == 0) return 0;
    return 1;
}

static void rec(int step, int j, int jp) {
    /* j = head positions placed (H=[1,j]), jp = q-side positions placed (M left end q-jp) */
    if (step == nsteps) {
        if (check_all()) { cnt++; report(); }
        return;
    }
    int p = order[step];
    int is_head = (p <= q / 2) ? 1 : 0;   /* head positions are 1..(q/2)-ish; decided by order construction */
    /* determine by construction: even steps are head positions, odd steps are q-side */
    is_head = (step % 2 == 0);
    for (int v = 1; v <= n; v++) {
        if (used[v] || v == q) continue;
        if (sym && p == 1 && v > q) break;
        if (p == 1 && splitK > 1 && ((v >> 1) % splitK) != splitR) continue;
        int ok = 1;
        for (int k = 1; k < m; k++) {
            int mask = (1 << k) - 1;
            int r = p & mask, vr = v & mask;
            if (res[k][r] >= 0) { if (res[k][r] != vr) { ok = 0; break; } }
            else if (resused[k][vr]) { ok = 0; break; }
        }
        if (!ok) continue;
        nodes++;
        int w = v ^ q;               /* partner value at position p + q */
        int nj = j, njp = jp;
        setval(p, v); setval(p + q, w);
        if (is_head) {
            nj = j + 1;                 /* H = [1, nj] ; partner at q + nj inside M = [q-jp, q+nj] */
            ok = check_ending(1, nj) && check_ending(q - jp, q + nj);
        } else {
            njp = jp + 1;               /* p = q - njp ; M = [q-njp, q+j] ; partner at 2q - njp inside T = [2q-njp, 2q-1] */
            ok = check_starting(q - njp, q + j) && check_starting(2 * q - njp, 2 * q - 1);
        }
        if (!ok) { a[p] = 0; a[p + q] = 0; setval(p, 0); setval(p + q, 0); continue; }
        used[v] = 1; used[w] = 1;
        int setk[12]; int nset = 0;
        for (int k = 1; k < m; k++) {
            int mask = (1 << k) - 1;
            int r = p & mask, vr = v & mask;
            if (res[k][r] < 0) { res[k][r] = vr; resused[k][vr] = 1; setk[nset++] = k; }
        }
        rec(step + 1, nj, njp);
        for (int i = 0; i < nset; i++) {
            int k = setk[i]; int mask = (1 << k) - 1;
            res[k][p & mask] = -1; resused[k][v & mask] = 0;
        }
        used[v] = 0; used[w] = 0;
        setval(p, 0); setval(p + q, 0);
    }
}

int main(int argc, char **argv) {
    if (argc < 2) { fprintf(stderr, "usage: goodperm_mid n [sym] [maxreport]\n"); return 2; }
    n = atoi(argv[1]); sym = argc > 2 ? atoi(argv[2]) : 0; maxreport = argc > 3 ? atoi(argv[3]) : 10;
    int t = n + 1; m = 0;
    while ((t & 1) == 0) { t >>= 1; m++; }
    if (t != 1 || m < 2 || n > MAXN) { fprintf(stderr, "n must be 2^m-1\n"); return 2; }
    q = (n + 1) / 2;
    for (int L = 0; L <= n + 1; L++) useL[L] = 1;
    if (argc > 5) { sscanf(argv[5], "%d,%d", &splitR, &splitK); if (splitK < 1) splitK = 1; }
    if (argc > 4 && argv[4][0] != '-') { for (int L = 0; L <= n + 1; L++) useL[L] = 0; char *s = argv[4]; while (*s) { int L = (int)strtol(s, &s, 10); if (L >= 0 && L <= n) useL[L] = 1; if (*s == ',') s++; } }
    for (int k = 0; k < 12; k++) for (int r = 0; r < 1024; r++) { res[k][r] = -1; resused[k][r] = 0; }
    for (int k = 1; k < m; k++) { res[k][0] = 0; resused[k][0] = 1; }
    for (int i = 0; i <= n + 1; i++) { a[i] = 0; pre[i] = 0; used[i] = 0; }
    /* order: 1, q-1, 2, q-2, ... covering 1..q-1 */
    nsteps = 0;
    for (int i = 1; nsteps < q - 1; i++) {
        order[nsteps++] = i;
        if (nsteps < q - 1) order[nsteps++] = q - i;
    }
    setval(q, q); used[q] = 1;
    clock_t c0 = clock();
    rec(0, 0, 0);
    printf("n=%d sym=%d split=%d/%d count=%lld nodes=%lld time=%.2fs\n", n, sym, splitR, splitK, cnt, nodes,
           (double)(clock() - c0) / CLOCKS_PER_SEC);
    return 0;
}
